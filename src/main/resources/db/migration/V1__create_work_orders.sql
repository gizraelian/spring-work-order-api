-- Fresh PostgreSQL schema matching WorkOrder and Hibernate's PostgreSQL mapping.
-- Existing deployments require a separately reviewed adoption/baseline procedure.
CREATE TABLE work_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(120) NOT NULL,
    description VARCHAR(2000),
    status VARCHAR(20) NOT NULL,
    priority VARCHAR(10) NOT NULL,
    requester_email VARCHAR(254) NOT NULL,
    due_date DATE,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT work_orders_status_check CHECK (status IN ('OPEN', 'IN_PROGRESS', 'COMPLETED', 'CANCELLED')),
    CONSTRAINT work_orders_priority_check CHECK (priority IN ('LOW', 'MEDIUM', 'HIGH'))
);
